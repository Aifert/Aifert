def seed_if_empty() -> None:
    with get_conn() as conn:
        count = conn.execute("SELECT COUNT(*) AS n FROM stops").fetchone()["n"]
        if count:
            return
        slugs: dict[str, int] = {}
        for stop in STOPS:
            row = conn.execute(
                """
                INSERT INTO stops (
                    slug, name, city, country, country_code, lat, lng,
                    timezone, arrive_at, depart_at, lodging_name,
                    lodging_address, confirmation, lodging_notes,
                    lodging_booked, sort_order
                ) VALUES (
                    %(slug)s, %(name)s, %(city)s, %(country)s,
                    %(country_code)s, %(lat)s, %(lng)s, %(timezone)s,
                    %(arrive_at)s, %(depart_at)s, %(lodging_name)s,
                    %(lodging_address)s, %(confirmation)s, %(lodging_notes)s,
                    %(lodging_booked)s, %(sort_order)s
                )
                RETURNING id
                """,
                stop,
            ).fetchone()
            slugs[stop["slug"]] = row["id"]
        for leg in LEGS:
            payload = dict(leg)
            payload["from_stop_id"] = (
                slugs.get(leg["from_slug"]) if leg["from_slug"] else None
            )
            payload["to_stop_id"] = (
                slugs.get(leg["to_slug"]) if leg["to_slug"] else None
            )
            del payload["from_slug"]
            del payload["to_slug"]
            conn.execute(
                """
                INSERT INTO legs (
                    from_stop_id, to_stop_id, kind, booked, carrier,
                    flight_no, confirmation, depart_at, arrive_at,
                    from_label, to_label, from_lat, from_lng, to_lat, to_lng,
                    notes, sort_order
                ) VALUES (
                    %(from_stop_id)s, %(to_stop_id)s, %(kind)s, %(booked)s,
                    %(carrier)s, %(flight_no)s, %(confirmation)s,
                    %(depart_at)s, %(arrive_at)s, %(from_label)s, %(to_label)s,
                    %(from_lat)s, %(from_lng)s, %(to_lat)s, %(to_lng)s,
                    %(notes)s, %(sort_order)s
                )
                """,
                payload,
            )
        for slug, day, title, notes, booked, optional, order in ACTIVITIES:
            conn.execute(
                """
                INSERT INTO activities (
                    stop_id, day, title, notes, booked, optional, sort_order
                ) VALUES (%s, %s, %s, %s, %s, %s, %s)
                """,
                (slugs[slug], day, title, notes, booked, optional, order),
            )
